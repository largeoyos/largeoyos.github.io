export function getBitmapGlyph(char: string): BitmapGlyph {
  if (CHINESE_8X8[char]) return CHINESE_8X8[char];
  const key = char.length === 1 ? char.toUpperCase() : '?';
  return FONT_5X7[key] ?? FONT_5X7['?'];
}

export function glyphWidth(char: string, scale = 1): number {
  const glyph = getBitmapGlyph(char);
  return (glyph[0]?.length ?? 5) * scale;
}

export function drawBitmapGlyph(
  context: CanvasRenderingContext2D,
  char: string,
  x: number,
  y: number,
  color: string,
  scale = 1,
) {
  const glyph = getBitmapGlyph(char);
  context.fillStyle = color;
  glyph.forEach((row, rowIndex) => {
    [...row].forEach((pixel, columnIndex) => {
      if (pixel === '1') {
        context.fillRect(
          Math.round(x + columnIndex * scale),
          Math.round(y + rowIndex * scale),
          scale,
          scale,
        );
      }
    });
  });
}

export function drawBitmapText(
  context: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  scale = 1,
  spacing = 1,
): number {
  let cursor = x;
  [...text].forEach(char => {
    drawBitmapGlyph(context, char, cursor, y, color, scale);
    cursor += glyphWidth(char, scale) + spacing;
  });
  return cursor;
}

export function bitmapTextWidth(text: string, scale = 1, spacing = 1): number {
  if (!text) return 0;
  return [...text].reduce((total, char) => total + glyphWidth(char, scale) + spacing, -spacing);
}
